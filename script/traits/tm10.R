validar_descricao <- function(texto) {
  
  # 1. vazio ou NA
  if (is.na(texto) || stringr::str_trim(texto) == "") {
    return(tibble(
      status = "vazio",
      processar = FALSE,
      qualitativo = FALSE,
      quantitativo = FALSE
    ))
  }
  
  texto_norm <- texto |>
    stringr::str_to_lower() |>
    stringi::stri_trans_general("Latin-ASCII")
  
  # 2. padrões de metadado
  padrao_metadado <- c(
    "disponivel em", "acesso em",
    "flora e funga", "jardim botanico",
    "world checklist", "herbario",
    "\\(sp\\)", "s\\.n\\."
  )
  
  if (stringr::str_detect(texto_norm, paste(padrao_metadado, collapse = "|"))) {
    return(tibble(
      status = "metadado",
      processar = FALSE,
      qualitativo = FALSE,
      quantitativo = FALSE
    ))
  }
  
  # 3. morfologia
  palavras_morfologicas <- c(
    "planta", "raiz", "rizoma", "ramicaule",
    "folha", "bainha", "infloresc",
    "pedunculo", "bractea",
    "sepala", "petala", "labelo",
    "coluna", "antera", "ovario"
  )
  
  tem_morfologia <- stringr::str_detect(
    texto_norm,
    paste(palavras_morfologicas, collapse = "|")
  )
  
  # 4. medidas
  tem_medidas <- stringr::str_detect(
    texto_norm,
    "\\d+[\\.,]?\\d*\\s*(–|-|×|x)\\s*\\d+[\\.,]?\\d*|\\d+[\\.,]?\\d*\\s*(mm|cm|m)"
  )
  
  # 5. decisão final
  if (tem_morfologia & tem_medidas) {
    return(tibble(
      status = "morfologia_com_medida",
      processar = TRUE,
      qualitativo = TRUE,
      quantitativo = TRUE
    ))
  }
  
  if (tem_morfologia & !tem_medidas) {
    return(tibble(
      status = "morfologia_sem_medida",
      processar = TRUE,
      qualitativo = TRUE,
      quantitativo = FALSE
    ))
  }
  
  return(tibble(
    status = "texto_nao_morfologico",
    processar = FALSE,
    qualitativo = FALSE,
    quantitativo = FALSE
  ))
}

