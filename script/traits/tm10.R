    return(tibble(
      status = "vazio",
      processar = FALSE,
      qualitativo = FALSE,
      quantitativo = FALSE
    ))
  }
  
  texto_norm <- texto |>
    stringr::str_to_lower() |>
    stringi::stri_trans_general("Latin-ASCII")
  
  # 2. metadados
  padrao_metadado <- c(
    "disponivel em", "acesso em",
    "flora e funga", "jardim botanico",
    "world checklist", "herbario",
    "\\(sp\\)", "s\\.n\\."
  )
  
