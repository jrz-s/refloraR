    return(tibble(
      status = "metadado",
      processar = FALSE,
      qualitativo = FALSE,
      quantitativo = FALSE
    ))
  }
  
  # 3. morfologia
  palavras_morfologicas <- c(
    "planta", "raiz", "rizoma", "ramicaule",
    "folha", "bainha", "infloresc",
