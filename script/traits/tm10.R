limpar_repeticoes <- function(texto, min_chars = 30) {
  
  if (is.na(texto) || stringr::str_trim(texto) == "")
    return(texto)
  
  # 1. normalização leve
  texto_norm <- texto |>
    stringr::str_replace_all("\\s+", " ") |>
    stringr::str_replace_all("\\s*([.;])\\s*", "\\1 ") |>
    stringr::str_trim()
  
  # 2. segmentação semântica
  segmentos <- stringr::str_split(texto_norm, "[.;]")[[1]] |>
    stringr::str_trim()
  
  # remove ruído curto
  segmentos <- segmentos[nchar(segmentos) >= min_chars]
  
  if (length(segmentos) <= 1)
    return(texto_norm)
  
  # 3. normalização para comparação
  keys <- segmentos |>
    stringr::str_to_lower() |>
    stringi::stri_trans_general("Latin-ASCII")
  
  # 4. remover duplicatas exatas
  keep <- !duplicated(keys)
  segmentos <- segmentos[keep]
  keys <- keys[keep]
  
  # 5. remover segmentos contidos em outros
  is_contained <- vapply(seq_along(keys), function(i) {
    any(keys[-i] |> stringr::str_detect(fixed(keys[i])))
  }, logical(1))
  
  segmentos_final <- segmentos[!is_contained]
  
  # 6. reconstrução
  paste(segmentos_final, collapse = ". ")
}

