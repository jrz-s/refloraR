eh_descricao_ontologica <- function(texto, min_ratio = 0.03) {
  
  if (is.na(texto) || stringr::str_trim(texto) == "")
    return(FALSE)
  
  n_colon <- stringr::str_count(texto, ":")
  n_semicolon <- stringr::str_count(texto, ";")
  
  n_tokens <- stringr::str_count(texto, "\\S+")
  
  ratio <- (n_colon + n_semicolon) / max(n_tokens, 1)
  
  (n_colon >= 2) && (n_semicolon >= 2) && (ratio >= min_ratio)
}

